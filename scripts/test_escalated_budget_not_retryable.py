#!/usr/bin/env python3
"""Stop granting a THIRD attempt once the escalated budget already failed.

GHO-3 diagnosis (2026-10-13): of 175 should_apply jobs in the last 30 days,
48 were never attempted at all (pure queue backlog from a broken run cadence
- see the GHO-3 issue comment, not this file's concern) and 11 were "stuck"
after burning all 3 attempts. One measured, narrow slice of that stuck tail:
`agent_driver.step_budget()` already escalates a retry to
AGENT_STEPS_ESCALATED (100 steps) whenever the previous failure was budget/
time exhaustion, on the theory the job was 90%+ through a long form and just
needed room (module4/agent_driver.py, evidence from 2026-09-02/03). That is
correct and must keep working for a FIRST miss.

But job 936 (Litware, Software Engineer, Tech Solutions) got that
exact escalation on its 2nd attempt, exhausted the full 100 steps again, and
was never recovered across all 3 allowed attempts (data/jobs.db:
module4_attempts=3, module4_last_status="stuck:ran out of step budget (100
model steps) mid-form, before submitting"). Before this fix, blockers.py
would have let a 3rd attempt spend another full escalated budget (~100 model
steps, ~1800s wall-clock) chasing a form that already proved it needs more
than the one escalation this job gets.

Run: uv run python scripts/test_escalated_budget_not_retryable.py

Deliberately raw-sqlite3, not the ORM/runner: this reads data/jobs.db directly
so the test stays valid regardless of in-flight schema or runner changes from
other concurrent work on this checkout (e.g. the module4_outcome column), and
so it only exercises the one thing this fix touches, module4/blockers.py.
"""

from __future__ import annotations

import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from module4 import agent_driver, blockers, runner  # noqa: E402

REPO = Path(__file__).resolve().parent.parent
DB_PATH = REPO / "data" / "jobs.db"

results: list[tuple[str, bool, str]] = []


def check(label: str, ok: bool, note: str = "") -> None:
    results.append((label, ok, note))
    print(f"  {'PASS' if ok else 'FAIL'}  {label:62s} {note}")


# The REAL stored detail for job 936, pulled from data/jobs.db on 2026-10-13.
# Code-generated by agent_driver.run_apply_agent, never LLM prose - see the
# comment on _ESCALATED_BUDGET_STILL_EXHAUSTED in module4/blockers.py.
JOB936_STATUS = "stuck:ran out of step budget (100 model steps) mid-form, before submitting"

# job 1501 (Ironbark): a FIRST-attempt budget miss at the plain (not
# escalated) budget. Must still be retried with the escalation, not dropped.
JOB1501_STATUS = "stuck:ran out of step budget (80 model steps) mid-form, before submitting"

# A plain retry-budget (50 steps) miss: also not permanent.
HALF_BUDGET_STATUS = "stuck:ran out of step budget (50 model steps) mid-form, before submitting"


def main() -> int:
    print("A. Offline: the real job936 failure is now permanent")
    check(
        "job936's stored detail mentions the escalated step count",
        str(agent_driver.AGENT_STEPS_ESCALATED) in JOB936_STATUS,
        f"AGENT_STEPS_ESCALATED={agent_driver.AGENT_STEPS_ESCALATED}",
    )
    reason = blockers.permanent_reason_from_last_status(JOB936_STATUS)
    check("permanent_reason_from_last_status fires on job936's real status", bool(reason), str(reason))

    print("\nB. A first-attempt (non-escalated) budget miss must NOT be dropped")
    check(
        "job1501's plain-budget miss (80 steps) stays retryable",
        blockers.permanent_reason_from_last_status(JOB1501_STATUS) is None,
    )
    check(
        "a half-budget retry miss (50 steps) stays retryable",
        blockers.permanent_reason_from_last_status(HALF_BUDGET_STATUS) is None,
    )
    check(
        "the escalation itself still fires for a first-time budget exhaustion",
        runner._is_budget_exhaustion(JOB1501_STATUS),
        "agent_driver.step_budget(is_retry=True, budget_boost=True) still applies",
    )

    print("\nC. Replay proof: job 936's REAL stored row, read straight from data/jobs.db")
    if not DB_PATH.is_file():
        print(f"  SKIP: no DB at {DB_PATH}")
        check("replay against the real row", True, "skipped, DB absent")
    else:
        con = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
        try:
            row = con.execute(
                "SELECT company_name, job_title, module4_attempts, module4_last_status "
                "FROM jobs WHERE id = 936"
            ).fetchone()
        finally:
            con.close()

        if row is None:
            print("  SKIP: job 936 not present in this DB snapshot")
            check("replay against the real row", True, "skipped, row absent")
        else:
            company, title, attempts, last_status = row
            print(f"  job 936: {company!r} - {title!r}")
            print(f"  stored module4_attempts: {attempts}")
            print(f"  stored module4_last_status: {last_status!r}")
            check(
                "the DB row still carries the escalated-exhaustion signature",
                bool(last_status)
                and str(agent_driver.AGENT_STEPS_ESCALATED) in last_status
                and "ran out of step budget" in last_status,
                str(last_status),
            )
            check(
                "blockers.permanent_reason_from_last_status drops the real row",
                bool(blockers.permanent_reason_from_last_status(last_status)),
                str(blockers.permanent_reason_from_last_status(last_status)),
            )

    passed = sum(1 for _, ok, _ in results if ok)
    print(f"\n{passed}/{len(results)} passed")
    if passed != len(results):
        print("\nFailures:")
        for label, ok, note in results:
            if not ok:
                print(f"  {label}: {note}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
